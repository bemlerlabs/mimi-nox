// ── Detect language ──────────────────────────────────────────────────────────
function detectLanguage() {
  // 1. Check localStorage override
  const stored = localStorage.getItem('mimi-nox-lang');
  if (stored && translations[stored]) return stored;

  // 2. Check browser language
  const browserLang = (navigator.language || navigator.userLanguage || 'en').substring(0, 2);
  return translations[browserLang] ? browserLang : 'en';
}

let _currentLang = detectLanguage();

/**
 * Get translation for a key.
 * @param {string} key - Dot-notation key (e.g. 'welcome.heading')
 * @param {Record<string, string>} [vars] - Optional interpolation variables
 * @returns {string} Translated string or key as fallback
 */
export function t(key, vars) {
  const str = translations[_currentLang]?.[key] || translations.en?.[key] || key;
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? `{${k}}`);
}

/**
 * Current active language code.
 */
export function currentLang() {
  return _currentLang;
}

/**
 * Switch language and re-apply all translations.
 * @param {'de'|'en'} lang
 */
export function setLanguage(lang) {
  if (!translations[lang]) return;
  _currentLang = lang;
  localStorage.setItem('mimi-nox-lang', lang);
  document.documentElement.lang = lang;
  applyTranslations();
}

/**
 * Apply translations to all elements with data-i18n attributes.
 * Supports:
 *   data-i18n="key"                → textContent
 *   data-i18n-placeholder="key"    → placeholder
 *   data-i18n-title="key"          → title
 *   data-i18n-aria="key"           → aria-label
 *   data-i18n-html="key"           → innerHTML (use sparingly)
 */
export function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  // Resolve data-prompt from i18n keys (for welcome cards)
  document.querySelectorAll('[data-i18n-prompt]').forEach(el => {
    el.dataset.prompt = t(el.dataset.i18nPrompt);
  });
}

/**
 * Check if user has never explicitly chosen a language.
 * Returns true on first launch (before any language selection).
 */
export function needsLanguageSelection() {
  return !localStorage.getItem('mimi-nox-lang');
}

export default { t, currentLang, setLanguage, applyTranslations, needsLanguageSelection, translations };
